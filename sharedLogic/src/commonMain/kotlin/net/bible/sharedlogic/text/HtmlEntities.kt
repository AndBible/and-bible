/**
 * Common replacement for commons-text `StringEscapeUtils.unescapeHtml4`: the BASIC, ISO8859_1 and
 * HTML40_EXTENDED named entities plus numeric `&#...;` / `&#x...;` entities (the semicolon is required).
 * Unknown or malformed entities are left as they are.
 *
 * The entity table is copied from Apache commons-text 1.9 `EntityArrays` (Apache License 2.0).
 */
object HtmlEntities {
    fun unescapeHtml4(text: String): String {
        if (text.indexOf('&') < 0) return text
        val sb = StringBuilder(text.length)
        var i = 0
        while (i < text.length) {
            val c = text[i]
            if (c != '&') {
                sb.append(c); i++; continue
            }
            val consumed = if (i + 2 < text.length && text[i + 1] == '#') numeric(text, i, sb) else named(text, i, sb)
            if (consumed > 0) i += consumed else { sb.append(c); i++ }
        }
        return sb.toString()
    }

    private fun named(text: String, start: Int, sb: StringBuilder): Int {
        val semi = text.indexOf(';', start + 1)
        if (semi < 0 || semi - start > MAX_NAME + 1) return 0
        val code = ENTITIES[text.substring(start + 1, semi)] ?: return 0
        sb.append(code.toChar())
        return semi - start + 1
    }

    // Mirrors commons-text NumericEntityUnescaper: hex digits are scanned even for decimal entities, and the
    // parse then fails (entity left as is) if the digits are not valid in the radix.
    private fun numeric(text: String, start: Int, sb: StringBuilder): Int {
        var p = start + 2
        val hex = text[p] == 'x' || text[p] == 'X'
        if (hex) p++
        var end = p
        while (end < text.length && (text[end] in '0'..'9' || text[end] in 'a'..'f' || text[end] in 'A'..'F')) end++
        if (end == p || end >= text.length || text[end] != ';') return 0
        val value = text.substring(p, end).toIntOrNull(if (hex) 16 else 10) ?: return 0
        when {
            value <= 0xFFFF -> sb.append(value.toChar())
            value <= 0x10FFFF -> {
                val v = value - 0x10000
                sb.append((0xD800 + (v shr 10)).toChar()).append((0xDC00 + (v and 0x3FF)).toChar())
            }
            else -> return 0
        }
        return end - start + 1
    }

