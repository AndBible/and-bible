import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.text.input.VisualTransformation
import net.bible.sharedui.strings.LocalStrings

/**
 * A single-line field for a secret (an API key): the text is masked by default and a trailing eye button
 * reveals or hides it. The reveal state is per field instance and is not kept across a new edit session.
 */
@Composable
fun AbSecretTextField(
    value: String,
    onValueChange: (String) -> Unit,
    label: String,
    modifier: Modifier = Modifier,
) {
    val strings = LocalStrings.current
    var revealed by rememberSaveable { mutableStateOf(false) }
    OutlinedTextField(
        value = value,
        onValueChange = onValueChange,
        singleLine = true,
        label = { androidx.compose.material3.Text(label) },
        visualTransformation = if (revealed) VisualTransformation.None else PasswordVisualTransformation(),
        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
        trailingIcon = {
            IconButton(onClick = { revealed = !revealed }) {
                Icon(
                    imageVector = if (revealed) Icons.Filled.VisibilityOff else Icons.Filled.Visibility,
                    contentDescription = if (revealed) strings.hideSecret else strings.showSecret,
                )
            }
        },
        modifier = modifier,
    )
}
