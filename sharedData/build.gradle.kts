// Generates a Kotlin source holding every committed Room schema export, so the commonTest
// suite can read them without file IO (iOS tests have no access to the module directory).
val generateSchemaFixtures by tasks.registering {
    val schemasDir = layout.projectDirectory.dir("schemas")
    val outDir = layout.buildDirectory.dir("generated/schemaFixtures/commonTest/kotlin")
    // KSP writes new schema exports into schemas/ (after a version bump); read them in the same build.
    mustRunAfter(tasks.matching { it.name.startsWith("ksp") && !it.name.contains("Test", ignoreCase = true) })
    inputs.dir(schemasDir)
    outputs.dir(outDir)
    doLast {
        fun literal(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
            .replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t") + "\""
        val exports = schemasDir.asFile.listFiles { f -> f.isDirectory }!!.sortedBy { it.name }.map { dir ->
            dir.name to dir.listFiles { f -> f.name.endsWith(".json") }!!
                .mapNotNull { f -> f.name.removeSuffix(".json").toIntOrNull()?.let { it to f } }.sortedBy { it.first }
        }
        val sb = StringBuilder("package net.bible.shareddata.fixtures\n\n// Generated by :sharedData:generateSchemaFixtures. Do not edit.\n\n")
        var n = 0
        val refs = mutableListOf<Triple<String, Int, String>>()
        exports.forEach { (db, files) ->
            files.forEach { (version, file) ->
                val fn = "json${n++}"
                // Chunked: a single JVM string constant is limited to 65535 bytes.
                val chunks = file.readText().chunked(12000).joinToString(",\n        ") { literal(it) }
                sb.append("private fun $fn(): String = listOf(\n        $chunks,\n    ).joinToString(\"\")\n\n")
                refs += Triple(db, version, fn)
            }
        }
        sb.append("object SchemaExports {\n    /** Database class FQN -> exported version -> raw schema JSON. */\n    val all: Map<String, Map<Int, String>> = mapOf(\n")
        refs.groupBy { it.first }.forEach { (db, list) ->
            sb.append("        ${literal(db)} to mapOf(\n")
            list.forEach { sb.append("            ${it.second} to ${it.third}(),\n") }
            sb.append("        ),\n")
        }
        sb.append("    )\n}\n")
        val out = outDir.get().asFile.resolve("net/bible/shareddata/fixtures/SchemaExports.kt")
        out.parentFile.mkdirs()
        out.writeText(sb.toString())
    }
}

