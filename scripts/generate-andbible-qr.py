#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["segno"]
# ///
"""Generate the AndBible homepage QR code as an Android vector drawable.

Usage: uv run scripts/generate-andbible-qr.py <output.xml>

Encodes https://andbible.org (error correction M) with a 4-module quiet zone. The drawable's viewport is
the module count including the quiet zone (1 unit = 1 module); it holds one white background path and one
black path with an `M x,y h1 v1 h-1 z` square per dark module. The colours are fixed so the code stays
scannable in every theme, monochrome included.
"""
import sys

import segno

URL = "https://andbible.org"
QUIET_ZONE = 4


def main(out: str) -> None:
    qr = segno.make(URL, error="m", micro=False, boost_error=False)
    matrix = [list(row) for row in qr.matrix]
    size = len(matrix) + 2 * QUIET_ZONE
    squares = "".join(
        f"M{x + QUIET_ZONE},{y + QUIET_ZONE}h1v1h-1z"
        for y, row in enumerate(matrix)
        for x, dark in enumerate(row)
        if dark
    )
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-andbible-qr.py for {URL}; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
    <path
        android:fillColor="#FFFFFF"
        android:pathData="M0,0h{size}v{size}h-{size}z" />
    <path
        android:fillColor="#000000"
        android:pathData="{squares}" />
</vector>
"""
    with open(out, "w", encoding="utf-8") as f:
        f.write(xml)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
