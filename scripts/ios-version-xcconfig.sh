#!/usr/bin/env bash
# Writes iosApp/Config/Version.xcconfig (MARKETING_VERSION) from version.properties.
# No name suffix: Apple allows three integers only. CURRENT_PROJECT_VERSION is left to Base.xcconfig
# (the release script overrides it with the build number).
# Env: VERSION_FILE (see lib-version.sh), VERSION_XCCONFIG (output path override), AND_BIBLE_COMMIT (optional override).
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
source "$DIR/lib-version.sh"
OUT="${VERSION_XCCONFIG:-$DIR/../iosApp/Config/Version.xcconfig}"
name=$(version_name "")
if [ "${AND_BIBLE_COMMIT+x}" = x ]; then
    commit="$AND_BIBLE_COMMIT"
    [[ "$commit" =~ ^[[:xdigit:]]{40}$ ]] || { echo "ios version: AND_BIBLE_COMMIT must be a 40-character git hash" >&2; exit 1; }
else
    commit=$(git -C "$DIR/.." rev-parse --verify HEAD 2>/dev/null || true)
    [[ "$commit" =~ ^[[:xdigit:]]{40}$ ]] || commit=""
fi
mkdir -p "$(dirname "$OUT")"
printf '// Generated by scripts/ios-version-xcconfig.sh from version.properties; do not edit or commit.\nMARKETING_VERSION = %s\nAND_BIBLE_COMMIT = %s\n' "$name" "$commit" > "$OUT"
