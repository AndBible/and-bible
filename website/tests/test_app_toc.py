"""The app's user guide TOC (UserGuideToc.kt) is generated from zensical.toml, the docs H1s and tutorials.yaml."""

from __future__ import annotations

import pytest

from sitegen import app_toc, paths

NAV = """\
[project]
nav = [
  { "Home" = "index.md" },
  { "Basics" = ["a.md", { "Sub" = ["sub/index.md", "sub/b.md"] }, "c.md"] },
  { "Help" = ["d.md", { "Releases" = ["releases/index.md"] }] },
  { "More" = ["style.md"] },
]
"""

TUTORIALS = """\
placeholder: RlLkpKZZwTg
episodes:
  - {slug: whats-new-6-0, number: null, title: "What's new", docs: a, anchor: null, youtube: null}
  - {slug: tutorial-01-first, number: 1, title: "First", docs: a, anchor: null, youtube: null}
  - {slug: tutorial-02-second, number: 2, title: "Second", docs: a, anchor: null, youtube: null}
  - {slug: tutorial-03-other, number: 3, title: "Other", docs: releases/index, anchor: null, youtube: null}
"""


def make_site(tmp_path, titles=None):
    docs = tmp_path / "docs"
    for stem, title in (titles or {"index": "Home", "a": "Page A", "sub/index": "Sub", "sub/b": "B",
                                   "c": "C", "d": "D", "releases/index": "Rel", "style": "S"}).items():
        path = docs / f"{stem}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(f"# {title}\n\nText\n")
    (tmp_path / "zensical.toml").write_text(NAV)
    (tmp_path / "tutorials.yaml").write_text(TUTORIALS)
    return tmp_path / "zensical.toml", docs, tmp_path / "tutorials.yaml"


@pytest.mark.parametrize("text, expected", [
    ("# Plain\n\nbody", "Plain"),
    ("# With id {#some-id}\n", "With id"),
    ("\n# **Bold** and *it*\n", "Bold and it"),
    ("```\n# not it\n```\n# Real\n", "Real"),
])
def test_h1_title_extraction(text, expected):
    assert app_toc.h1_title(text, "x.md") == expected


def test_h1_missing_raises():
    with pytest.raises(ValueError, match="x.md"):
        app_toc.h1_title("no title\n## sub\n", "x.md")


def test_sections_follow_the_nav_and_skip_more_and_releases(tmp_path):
    toml, docs, yaml_ = make_site(tmp_path)
    toc = app_toc.build(toml, docs, yaml_)
    assert [(s.title, [p.stem for p in s.pages]) for s in toc.sections] == [
        ("Basics", ["a", "sub", "sub/b", "c"]),  # the Customisation-style sub-group is flattened in order
        ("Help", ["d"]),
    ]
    assert [p.title for p in toc.sections[0].pages] == ["Page A", "Sub", "B", "C"]


def test_episodes_attach_to_their_docs_page(tmp_path):
    toml, docs, yaml_ = make_site(tmp_path)
    toc = app_toc.build(toml, docs, yaml_)
    page_a = toc.sections[0].pages[0]
    assert page_a.episodes == ["WHATS_NEW_6_0", "TUTORIAL_01_FIRST", "TUTORIAL_02_SECOND"]
    assert "TUTORIAL_03_OTHER" not in [e for s in toc.sections for p in s.pages for e in p.episodes]
    assert toc.episode_titles["TUTORIAL_01_FIRST"] == "1. First"
    assert toc.episode_titles["WHATS_NEW_6_0"] == "What's new"


def test_kotlin_output_is_deterministic_and_escaped(tmp_path):
    titles = {"index": "Home", "a": 'Say "hi" costs $5 \\ now', "sub/index": "Sub", "sub/b": "B",
              "c": "C", "d": "D", "releases/index": "Rel", "style": "S"}
    toml, docs, yaml_ = make_site(tmp_path, titles)
    first = app_toc.render(app_toc.build(toml, docs, yaml_))
    assert first == app_toc.render(app_toc.build(toml, docs, yaml_))
    assert 'Page("a", "Say \\"hi\\" costs \\$5 \\\\ now", DocsLinks.page("a")' in first
    assert 'DocsLinks.page("sub")' in first  # an index page links its directory
    assert first.startswith("package net.bible.sharedcore.docs")
    assert "GENERATED by website/sitegen/app_toc.py" in first
    assert "Other" not in first.split("episodeTitles", 1)[0]


def test_generated_file_is_up_to_date():
    expected = app_toc.render(app_toc.build())
    assert app_toc.OUTPUT.read_text(encoding="utf-8") == expected, "run: cd website && uv run python -m sitegen.app_toc"


def test_every_toc_page_stem_is_a_published_docs_page():
    toc = app_toc.build()
    assert all((paths.CONTENT / "en" / "docs" / f"{p.stem}.md").is_file() or
               (paths.CONTENT / "en" / "docs" / p.stem / "index.md").is_file()
               for s in toc.sections for p in s.pages)
