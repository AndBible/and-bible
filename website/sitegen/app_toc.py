"""Generate sharedCore `UserGuideToc.kt` and the owned block in `app/src/main/res/values/strings.xml`.

Sections and order come from `zensical.toml` `nav`, page titles from each docs page's H1 and the episodes of a page
from `data/tutorials.yaml`. `uv run python -m sitegen.app_toc` writes both outputs; `--check` fails when either is stale.
Never reads the private video pipeline.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
import tomllib
from xml.sax.saxutils import escape
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from sitegen import paths

OUTPUT = paths.REPO / "sharedCore/src/commonMain/kotlin/net/bible/sharedcore/docs/UserGuideToc.kt"
STRINGS = paths.REPO / "app/src/main/res/values/strings.xml"
BEGIN = "    <!-- BEGIN generated by sitegen.app_toc, do not edit -->"
END = "    <!-- END generated by sitegen.app_toc, do not edit -->"
SKIPPED_SECTIONS = {"Home", "More"}
SKIPPED_GROUPS = {"Releases"}


@dataclass(frozen=True)
class Page:
    stem: str
    title: str
    episodes: list[str]  # TutorialVideos.Episode constant names

    @property
    def key(self) -> str:
        return "user_guide_page_" + _key(self.stem)


@dataclass(frozen=True)
class Section:
    title: str
    pages: list[Page]

    @property
    def key(self) -> str:
        # Heading-derived keys mean renaming a heading orphans its translations.
        return "user_guide_section_" + _key(self.title)


@dataclass(frozen=True)
class EpisodeTitle:
    key: str
    title: str
    number: int | None


@dataclass(frozen=True)
class Toc:
    sections: list[Section]
    episode_titles: dict[str, EpisodeTitle]


def h1_title(text: str, source: str) -> str:
    """The first Markdown `# ` heading outside code fences, without `{#id}` attributes and emphasis."""
    in_fence = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        elif not in_fence and line.startswith("# "):
            title = re.sub(r"\s*\{[^}]*\}\s*$", "", line[2:].strip())
            title = re.sub(r"(\*\*|__)(.+?)\1", r"\2", title)
            title = re.sub(r"(?<![\w*])\*(.+?)\*(?![\w*])", r"\1", title)
            return title.strip()
    raise ValueError(f"{source}: no H1 heading")


def _stem(page: str) -> str:
    stem = page.removesuffix(".md")
    return stem.removesuffix("/index") if stem.endswith("/index") else stem


def _is_link(entry: str) -> bool:
    """A nav link (`/videos/`, `https://...`) rather than a docs page; the app TOC lists pages only."""
    return not entry.endswith(".md")


def _flatten(node: Any) -> list[str]:
    if isinstance(node, str):
        return [] if _is_link(node) else [node]
    if isinstance(node, list):
        return [p for item in node for p in _flatten(item)]
    if isinstance(node, dict):
        return [p for key, value in node.items() if key not in SKIPPED_GROUPS for p in _flatten(value)]
    return []


def _const(slug: str) -> str:
    return slug.upper().replace("/", "_").replace("-", "_")


def _key(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def build(toml: Path = paths.WEBSITE / "zensical.toml", docs: Path = paths.CONTENT / "en" / "docs",
          tutorials: Path = paths.DATA / "tutorials.yaml") -> Toc:
    data = yaml.safe_load(tutorials.read_text(encoding="utf-8")) or {}
    episodes = data.get("episodes", [])
    by_docs: dict[str, list[str]] = {}
    titles: dict[str, EpisodeTitle] = {}
    for episode in episodes:
        const = _const(episode["slug"])
        by_docs.setdefault(episode["docs"], []).append(const)
        number = episode.get("number")
        slug = episode["slug"].removeprefix("tutorial-")
        titles[const] = EpisodeTitle("tutorial_title_" + _key(slug), episode["title"], number)
    sections = []
    for entry in tomllib.loads(toml.read_text(encoding="utf-8"))["project"]["nav"]:
        (name, node), = entry.items()
        if name in SKIPPED_SECTIONS:
            continue
        pages = []
        for page in _flatten(node):
            source = docs / page
            stem = _stem(page)
            pages.append(Page(stem, h1_title(source.read_text(encoding="utf-8"), str(source)), by_docs.get(stem, [])))
        sections.append(Section(name, pages))
    return Toc(sections, titles)


def _k(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def render(toc: Toc) -> str:
    out = [
        "package net.bible.sharedcore.docs",
        "",
        "// GENERATED by website/sitegen/app_toc.py — do not edit. Regenerate: cd website && uv run python -m sitegen.app_toc",
        "object UserGuideToc {",
        "    data class Page(val stem: String, val title: String, val key: String, val url: String, val episodes: List<TutorialVideos.Episode>) {",
        "        /** The episodes with a YouTube id; use this when a view specifically needs published videos. */",
        "        val publishedEpisodes: List<TutorialVideos.Episode> get() = episodes.filter { it.youtubeId != null }",
        "    }",
        "",
        "    data class Section(val title: String, val key: String, val pages: List<Page>)",
        "",
        "    data class EpisodeTitle(val key: String, val title: String, val number: Int?)",
        "",
        "    val sections: List<Section> = listOf(",
    ]
    for section in toc.sections:
        out.append(f'        Section("{_k(section.title)}", "{section.key}", listOf(')
        for page in section.pages:
            eps = ", ".join(f"TutorialVideos.Episode.{e}" for e in page.episodes)
            link = _const(page.stem)
            out.append(f'            Page("{_k(page.stem)}", "{_k(page.title)}", "{page.key}", DocsLink.{link}.url, listOf({eps})),')
        out.append("        )),")
    out += [
        "    )",
        "",
        "    /** English fallback titles and separate episode numbers. */",
        "    val episodeTitles: Map<TutorialVideos.Episode, EpisodeTitle> = mapOf(",
    ]
    for const, title in toc.episode_titles.items():
        number = title.number if title.number is not None else "null"
        out.append(f'        TutorialVideos.Episode.{const} to EpisodeTitle("{title.key}", "{_k(title.title)}", {number}),')
    out += [
        "    )",
        "}",
        "",
    ]
    return "\n".join(out)


def render_strings(toc: Toc) -> str:
    entries = [(s.key, s.title) for s in toc.sections]
    entries += [(p.key, p.title) for s in toc.sections for p in s.pages]
    entries += [(e.key, e.title) for e in toc.episode_titles.values()]
    if len({key for key, _ in entries}) != len(entries):
        raise ValueError("duplicate user guide resource keys")
    lines = [BEGIN]
    for key, title in entries:
        escaped_title = title.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
        if escaped_title.startswith(("@", "?")):
            escaped_title = "\\" + escaped_title
        value = escape(escaped_title)
        lines.append(f'    <string name="{key}">{value}</string>')
    return "\n".join(lines + [END])


def update_strings(current: str, block: str) -> str:
    if BEGIN in current or END in current:
        if current.count(BEGIN) != 1 or current.count(END) != 1 or current.index(BEGIN) > current.index(END):
            raise ValueError("invalid generated user guide block")
        start = current.index(BEGIN)
        end = current.index(END) + len(END)
        return current[:start] + block + current[end:]
    if current.count("</resources>") != 1:
        raise ValueError("expected one resources closing tag")
    return current.replace("</resources>", block + "\n</resources>")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when generated output is stale")
    args = parser.parse_args(argv)
    toc = build()
    kotlin = render(toc)
    current_strings = STRINGS.read_text(encoding="utf-8")
    strings = update_strings(current_strings, render_strings(toc))
    current_kotlin = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
    if args.check:
        stale = False
        for path, current, generated in [(OUTPUT, current_kotlin, kotlin), (STRINGS, current_strings, strings)]:
            if current != generated:
                sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), generated.splitlines(True), str(path), "generated"))
                stale = True
        return int(stale)
    OUTPUT.write_text(kotlin, encoding="utf-8")
    STRINGS.write_text(strings, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
