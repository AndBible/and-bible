"""Generate the app's user guide table of contents (sharedCore `UserGuideToc.kt`).

Sections and order come from `zensical.toml` `nav`, page titles from each docs page's H1 and the episodes of a page
from `data/tutorials.yaml`. `uv run python -m sitegen.app_toc` writes the file, `--check` fails when it is stale.
Never reads the private video pipeline.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from sitegen import paths

OUTPUT = paths.REPO / "sharedCore/src/commonMain/kotlin/net/bible/sharedcore/docs/UserGuideToc.kt"
SKIPPED_SECTIONS = {"Home", "More"}
SKIPPED_GROUPS = {"Releases"}


@dataclass(frozen=True)
class Page:
    stem: str
    title: str
    episodes: list[str]  # TutorialVideos.Episode constant names


@dataclass(frozen=True)
class Section:
    title: str
    pages: list[Page]


@dataclass(frozen=True)
class Toc:
    sections: list[Section]
    episode_titles: dict[str, str]


def h1_title(text: str, source: str) -> str:
    """The first Markdown `# ` heading outside code fences, without `{#id}` attributes and emphasis."""
    in_fence = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        elif not in_fence and line.startswith("# "):
            title = re.sub(r"\s*\{[^}]*\}\s*$", "", line[2:].strip())
            title = re.sub(r"(\*\*|__)(.+?)\1", r"\2", title)
            title = re.sub(r"(?<![\w*])\*(.+?)\*(?![\w*])", r"\1", title)
            return title.strip()
    raise ValueError(f"{source}: no H1 heading")


def _stem(page: str) -> str:
    stem = page.removesuffix(".md")
    return stem.removesuffix("/index") if stem.endswith("/index") else stem


def _flatten(node: Any) -> list[str]:
    if isinstance(node, str):
        return [node]
    if isinstance(node, list):
        return [p for item in node for p in _flatten(item)]
    if isinstance(node, dict):
        return [p for key, value in node.items() if key not in SKIPPED_GROUPS for p in _flatten(value)]
    return []


def _const(slug: str) -> str:
    return slug.upper().replace("-", "_")


def build(toml: Path = paths.WEBSITE / "zensical.toml", docs: Path = paths.CONTENT / "en" / "docs",
          tutorials: Path = paths.DATA / "tutorials.yaml") -> Toc:
    data = yaml.safe_load(tutorials.read_text(encoding="utf-8")) or {}
    episodes = data.get("episodes", [])
    by_docs: dict[str, list[str]] = {}
    titles: dict[str, str] = {}
    for episode in episodes:
        const = _const(episode["slug"])
        by_docs.setdefault(episode["docs"], []).append(const)
        number = episode.get("number")
        titles[const] = f"{number}. {episode['title']}" if number is not None else episode["title"]
    sections = []
    for entry in tomllib.loads(toml.read_text(encoding="utf-8"))["project"]["nav"]:
        (name, node), = entry.items()
        if name in SKIPPED_SECTIONS:
            continue
        pages = []
        for page in _flatten(node):
            source = docs / page
            stem = _stem(page)
            pages.append(Page(stem, h1_title(source.read_text(encoding="utf-8"), str(source)), by_docs.get(stem, [])))
        sections.append(Section(name, pages))
    return Toc(sections, titles)


def _k(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def render(toc: Toc) -> str:
    out = [
        "package net.bible.sharedcore.docs",
        "",
        "// GENERATED by website/sitegen/app_toc.py — do not edit. Regenerate: cd website && uv run python -m sitegen.app_toc",
        "object UserGuideToc {",
        "    data class Page(val stem: String, val title: String, val url: String, val episodes: List<TutorialVideos.Episode>) {",
        "        /** The episodes with a YouTube id; use this when a view specifically needs published videos. */",
        "        val publishedEpisodes: List<TutorialVideos.Episode> get() = episodes.filter { it.youtubeId != null }",
        "    }",
        "",
        "    data class Section(val title: String, val pages: List<Page>)",
        "",
        "    val sections: List<Section> = listOf(",
    ]
    for section in toc.sections:
        out.append(f'        Section("{_k(section.title)}", listOf(')
        for page in section.pages:
            eps = ", ".join(f"TutorialVideos.Episode.{e}" for e in page.episodes)
            out.append(f'            Page("{_k(page.stem)}", "{_k(page.title)}", DocsLinks.page("{_k(page.stem)}"), listOf({eps})),')
        out.append("        )),")
    out += [
        "    )",
        "",
        "    /** Display titles of the series, e.g. \"1. Getting started: ...\"; \"What's new\" has no number. */",
        "    val episodeTitles: Map<TutorialVideos.Episode, String> = mapOf(",
    ]
    for const, title in toc.episode_titles.items():
        out.append(f'        TutorialVideos.Episode.{const} to "{_k(title)}",')
    out += [
        "    )",
        "}",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 with a diff when the file is stale")
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True), "current", "generated"))
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
