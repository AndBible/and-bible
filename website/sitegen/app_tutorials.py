"""Generate the app's tutorial video catalog from data/tutorials.yaml."""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

from sitegen import paths
from sitegen.tutorials import _LANG, youtube_language

OUTPUT = paths.REPO / "sharedCore/src/commonMain/kotlin/net/bible/sharedcore/docs/TutorialVideoCatalog.kt"


@dataclass(frozen=True)
class Catalog:
    placeholder_id: str | None
    placeholder_subtitles: tuple[str, ...]
    playlist_id: str | None
    episodes: tuple[tuple[str, str | None, tuple[str, ...]], ...]


def build(tutorials: Path = paths.DATA / "tutorials.yaml") -> Catalog:
    data = yaml.safe_load(tutorials.read_text(encoding="utf-8")) or {}
    placeholder = data.get("placeholder")
    if placeholder is not None and not re.fullmatch(r"[A-Za-z0-9_-]{11}", placeholder):
        raise ValueError("placeholder must be an 11-character YouTube id or null")
    placeholder_subtitles = _subtitles(data.get("placeholder_subtitles", []), "placeholder_subtitles")
    playlist = data.get("playlist")
    if playlist is not None and not re.fullmatch(r"[A-Za-z0-9_-]+", playlist):
        raise ValueError("playlist must be a YouTube playlist id or null")
    episodes = []
    seen_slugs: set[str] = set()
    for episode in data.get("episodes", []):
        slug, youtube = episode["slug"], episode.get("youtube")
        if not isinstance(slug, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            raise ValueError(f"bad episode slug {slug!r}")
        if slug in seen_slugs:
            raise ValueError(f"duplicate episode slug {slug}")
        seen_slugs.add(slug)
        if youtube is not None and not re.fullmatch(r"[A-Za-z0-9_-]{11}", youtube):
            raise ValueError(f"{slug}: youtube must be an 11-character YouTube id or null")
        episodes.append((slug, youtube, _subtitles(episode.get("subtitles", []), f"{slug}.subtitles")))
    return Catalog(placeholder, placeholder_subtitles, playlist, tuple(episodes))


def _subtitles(value: list[str], source: str) -> tuple[str, ...]:
    if not isinstance(value, list) or any(not isinstance(tag, str) or not tag for tag in value):
        raise ValueError(f"{source} must be a list of language tags")
    normalized = [youtube_language(code) for code in value]
    for code in normalized:
        if not _LANG.fullmatch(code):
            raise ValueError(f"{source} has a bad subtitle language {code!r}")
        if code == "en" or code.startswith("en-"):
            raise ValueError(f"{source} lists English; subtitles are the languages besides English")
    if normalized != sorted(set(normalized)):
        raise ValueError(f"{source} must be sorted and unique")
    return tuple(normalized)


def _k(value: str) -> str:
    escaped = []
    for char in value:
        escapes = {"\\": "\\\\", '"': '\\"', "$": "\\$", "\n": "\\n", "\r": "\\r", "\t": "\\t", "\b": "\\b"}
        if char in escapes:
            escaped.append(escapes[char])
        elif ord(char) < 0x20 or ord(char) == 0x7f:
            escaped.append(f"\\u{ord(char):04x}")
        else:
            escaped.append(char)
    return "".join(escaped)


def render(catalog: Catalog) -> str:
    out = [
        "package net.bible.sharedcore.docs", "",
        "// GENERATED by website/sitegen/app_tutorials.py — do not edit. Regenerate: cd website && uv run python -m sitegen.app_tutorials",
        "internal object TutorialVideoCatalog {",
        "    data class Video(val youtubeId: String?, val subtitles: Set<String>)",
        f'    val placeholderId: String? = {"null" if catalog.placeholder_id is None else chr(34) + _k(catalog.placeholder_id) + chr(34)}',
        f'    val placeholderSubtitles: Set<String> = setOf({", ".join(chr(34) + _k(tag) + chr(34) for tag in catalog.placeholder_subtitles)})',
        f'    val playlistId: String? = {"null" if catalog.playlist_id is None else chr(34) + _k(catalog.playlist_id) + chr(34)}',
        "    val episodes: Map<String, Video> = mapOf(",
    ]
    for slug, youtube, subtitles in catalog.episodes:
        youtube_value = "null" if youtube is None else f'"{_k(youtube)}"'
        subtitle_values = ", ".join(f'"{_k(tag)}"' for tag in subtitles)
        out.append(f'        "{_k(slug)}" to Video({youtube_value}, setOf({subtitle_values})),')
    out += ["    )", "}", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 with a diff when the file is stale")
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True), "current", "generated"))
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
