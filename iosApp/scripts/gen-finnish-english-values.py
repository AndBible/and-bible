#!/usr/bin/env python3
"""Generates iosApp/iosAppUITests/FinnishEnglishValues.swift: the English values of strings that DO have a different
values-fi translation, minus any text that is also the English of an untranslated key or already a Finnish value.
FinnishWalkUITests asserts none of them is an accessibility label on a walked screen in Finnish.
Run from the repo root: python3 iosApp/scripts/gen-finnish-english-values.py"""
import re
import xml.etree.ElementTree as ET

RES = "app/src/main/res/"
OUT = "iosApp/iosAppUITests/FinnishEnglishValues.swift"


def load(path):
    out = {}
    for node in ET.parse(path).getroot().iter("string"):
        if list(node) or node.get("translatable") == "false":
            continue  # markup children or not translatable
        text = (node.text or "").replace("\\'", "'").replace('\\"', '"')
        out[node.get("name")] = text.strip()
    return out


en, fi = load(RES + "values/strings.xml"), load(RES + "values-fi/strings.xml")
fi_values = {v.lower() for v in fi.values()}
untranslated = {en[k].lower() for k in en if k not in fi}
same = {en[k].lower() for k in en if k in fi and fi[k] == en[k]}
values = set()
for key, english in en.items():
    finnish = fi.get(key)
    if finnish is None or finnish == english:
        continue
    low = english.lower()
    if not (4 <= len(english) <= 60) or re.search(r"[%\\\n<>{}]|\.\.\.|…$", english):
        continue
    if low in fi_values or low in untranslated or low in same:
        continue
    values.add(english)
body = ",\n".join('    "%s"' % v.replace("\\", "\\\\").replace('"', '\\"') for v in sorted(values))
open(OUT, "w", encoding="utf-8").write(
    "// GENERATED by iosApp/scripts/gen-finnish-english-values.py: do not edit.\n"
    "/// English values of strings that have a different Finnish translation (%d)\n"
    "let finnishEnglishValues: Set<String> = [\n%s\n]\n" % (len(values), body))
print(len(values), "values")
